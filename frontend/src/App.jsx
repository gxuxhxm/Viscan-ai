// ── Utility helpers ──────────────────────────────────────────────────────────

function initials(name) {
  return name ? name.split(' ').map(w => w[0]).join('').toUpperCase().slice(0, 2) : '?';
}

function reportTypeBadgeClass(type) {
  const map = { OPG: 'badge-opg', PERIAPICAL: 'badge-periapical', BITEWING: 'badge-bitewing', CBCT: 'badge-cbct' };
  return map[type] || '';
}

function severityClass(sev) {
  const map = { none: 'severity-none', mild: 'severity-mild', moderate: 'severity-moderate', severe: 'severity-severe' };
  return map[(sev || '').toLowerCase()] || 'severity-unspecified';
}

function formatDate(d) {
  if (!d) return '';
  const dt = new Date(d + 'T00:00:00');
  return dt.toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' });
}

// Sidebar meta line: how many reports are on file for the patient. Falls back
// to an empty string when the count is missing (older payload).
function patientListMeta(patient) {
  const count = patient.report_count;
  if (typeof count !== 'number') return '';
  return count === 0 ? 'No reports yet' : `${count} ${count === 1 ? 'report' : 'reports'}`;
}

// ── Draft export helpers ─────────────────────────────────────────────────────
// One filename segment: keeps letters and digits in any script, collapses
// everything else to "_" and falls back when nothing usable is left, so a
// missing name/id never produces a broken filename.
function filenamePart(value, fallback) {
  const cleaned = String(value ?? '')
    .normalize('NFKC')
    .replace(/[^\p{L}\p{N}]+/gu, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 60);
  return cleaned || fallback;
}

// Priyanka Sharma + R004 → Priyanka_Sharma_R004_Draft.txt
function draftExportFilename(report, patient) {
  return `${filenamePart(patient?.name, 'Patient')}_${filenamePart(report?.id, 'Report')}_Draft.txt`;
}

