// ── Findings list ────────────────────────────────────────────────────────────
// Findings tagged with a historical/current context render as two clearly
// labelled sections; untagged findings (saved reports) render as a plain list.
const FINDING_GROUPS = [
  { key: 'historical', label: 'Historical findings (prior studies)' },
  { key: 'current', label: 'Current observations' },
  { key: '', label: 'Other findings' },
];

function FindingList({ findings }) {
  if (!findings?.length) return null;
  const isGrouped = findings.some(f => CONTEXT_LABELS[(f.context || '').toLowerCase()]);
  if (!isGrouped) {
    return findings.map((f, i) => <FindingCard key={i} finding={f} />);
  }
  return FINDING_GROUPS.map(({ key, label }) => {
    const items = findings.filter(f => (f.context || '').toLowerCase() === key);
    if (!items.length) return null;
    return (
      <div key={key || 'untagged'} style={{ marginBottom: 12 }}>
        <div className="type-eyebrow" style={{ marginBottom: 6, color: 'var(--color-ink-muted)' }}>
          {label}
        </div>
        {items.map((f, i) => <FindingCard key={i} finding={f} />)}
      </div>
    );
  });
}

// ── Full Report Detail ───────────────────────────────────────────────────────
// Draft edits live in the parent (keyed by report id) so they survive opening
// another report and coming back; they are only ever written by export, and
// never back onto the saved report.
function ReportDetail({ report, patient, draftText, onDraftChange }) {
  const [showDraft, setShowDraft] = useState(false);
  const draftId = useId();
  const draftPanelId = useId();

  if (!report) return null;

  // The editable content: local edits for this report, else the saved draft.
  const draftValue = draftText ?? (report.draft_report || '');
  const hasSavedDraft = Boolean((report.draft_report || '').trim());
  // Grow with the content so long multiline drafts stay readable (capped).
  const draftRows = Math.min(Math.max(draftValue.split('\n').length + 1, 10), 60);

  // Export: a Blob of the edited draft text only; no report header, no page
  // chrome, no browser print dialog, and no write-back to the original report.
  const handleExportDraft = () => {
    const blob = new Blob([draftValue], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = draftExportFilename(report, patient);
    document.body.appendChild(link);
    link.click();
    link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 0);
  };

  const metaLine = [
    report.encounter_type,
    report.tooth_number ? `Tooth ${report.tooth_number}` : null,
  ].filter(Boolean).join(' · ');

  return (
    <div className="animate-fade-up print-doc" style={{ padding: 24, paddingBottom: 32, display: 'flex', flexDirection: 'column', gap: 20, minHeight: '100%' }}>
      {/* Header */}
      <div style={{ display: 'flex', gap: 12, alignItems: 'flex-start', justifyContent: 'space-between', flexWrap: 'wrap' }}>
        <div>
          <div style={{ display: 'flex', gap: 8, alignItems: 'center', marginBottom: 4, flexWrap: 'wrap' }}>
            <ReportTypeBadge type={report.type} />
            <span className="type-caption" style={{ color: 'var(--color-ink-muted)' }}>#{report.id}</span>
            <span className={`type-caption severity-${report.status === 'final' ? 'none' : 'mild'}`}
              style={{ padding: '1px 6px', borderRadius: 'var(--radius-xs)' }}>
              {report.status}
            </span>
          </div>
          <h2 className="type-card-title" style={{ margin: 0 }}>
            {report.type} Report
            {patient && <span style={{ fontWeight: 400, color: 'var(--color-ink-muted)' }}> · {patient.name}</span>}
          </h2>
          <div style={{ display: 'flex', gap: 16, marginTop: 6, flexWrap: 'wrap' }}>
            <span className="type-body-sm" style={{ color: 'var(--color-ink-muted)', display: 'flex', alignItems: 'center', gap: 4 }}>
              <Calendar size={13} /> {formatDate(report.date)}
            </span>
            <span className="type-body-sm" style={{ color: 'var(--color-ink-muted)', display: 'flex', alignItems: 'center', gap: 4 }}>
              <Stethoscope size={13} /> {report.radiologist}
            </span>
            {metaLine && (
              <span className="type-body-sm" style={{ color: 'var(--color-ink-muted)', display: 'flex', alignItems: 'center', gap: 4 }}>
                <Activity size={13} /> {metaLine}
              </span>
            )}
          </div>
        </div>
      </div>

      {/* Findings */}
      <div>
        <h3 className="type-eyebrow" style={{ marginBottom: 10, color: 'var(--color-ink-muted)', textTransform: 'none' }}>
          Findings ({report.findings?.length || 0})
        </h3>
        <FindingList findings={report.findings} />
      </div>

      {/* Impression */}
      <div className="card" style={{ borderLeft: '3px solid var(--color-ink)', borderRadius: '0 var(--radius-lg) var(--radius-lg) 0' }}>
        <div className="type-eyebrow" style={{ marginBottom: 6, color: 'var(--color-ink-muted)' }}>Impression</div>
        <p className="type-body" style={{ margin: 0 }}>{report.impression}</p>
      </div>

      {/* Proposed billing (synthetic, never verified) */}
      {report.billing_codes && (
        <p className="type-caption" style={{ color: 'var(--color-ink-tertiary)', margin: 0 }}>
          Proposed billing (not verified): ICD-10 {report.billing_codes.icd_10 || 'N/A'} · CDT {report.billing_codes.cdt_proposed || 'N/A'}
        </p>
      )}

      {/* Draft Report Toggle + TXT export */}
      <div>
        <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
          <button className="btn-secondary" onClick={() => setShowDraft(s => !s)}
            aria-expanded={showDraft} aria-controls={draftPanelId}
            style={{ flex: 1, justifyContent: 'space-between', minHeight: 36, fontSize: 13, padding: '6px 12px' }}>
            <span style={{ display: 'flex', alignItems: 'center', gap: 6 }}>
              <FileText size={14} /> Draft Report
            </span>
            <ChevronDown size={14} style={{ transform: showDraft ? 'rotate(180deg)' : 'none', transition: 'transform 0.2s' }} />
          </button>
          <button className="btn-secondary" onClick={handleExportDraft}
            disabled={!draftValue.trim()}
            aria-label="Export draft report as a .txt file"
            title={draftValue.trim()
              ? 'Download the edited draft as a .txt file'
              : 'The draft is empty, nothing to export'}
            style={{ minHeight: 36, fontSize: 13, padding: '6px 12px', gap: 6 }}>
            <Download size={14} /> Export Draft (.txt)
          </button>
        </div>
        {showDraft && (
          <div id={draftPanelId} className="animate-fade-up" style={{
            marginTop: 8, background: 'var(--color-surface-1)', border: '1px solid var(--color-hairline)',
            borderRadius: 'var(--radius-md)', padding: 16,
          }}>
            <div style={{
              display: 'flex', justifyContent: 'space-between', alignItems: 'baseline',
              gap: 8, marginBottom: 8, flexWrap: 'wrap',
            }}>
              <label htmlFor={draftId} className="type-eyebrow"
                style={{ color: 'var(--color-ink-muted)', display: 'inline-flex', alignItems: 'center', gap: 4 }}>
                <Edit3 size={13} /> Editable draft
              </label>
              <span className="type-caption" style={{ color: 'var(--color-ink-tertiary)' }}>
                Edits are kept locally until exported; the saved report is unchanged.
              </span>
            </div>
            {!hasSavedDraft && (
              <p className="type-caption" style={{
                color: 'var(--color-ink-muted)', margin: '0 0 8px',
                display: 'flex', alignItems: 'center', gap: 4,
              }}>
                <Info size={12} /> This report has no saved draft text; type the draft below.
              </p>
            )}
            <textarea
              id={draftId}
              className="textarea-text type-mono"
              rows={draftRows}
              value={draftValue}
              onChange={e => onDraftChange(report.id, e.target.value)}
              placeholder="Type the draft report…"
              aria-label="Editable draft report"
              style={{ minHeight: 220, fontSize: 12, lineHeight: 1.7, resize: 'vertical' }}
            />
            <div className="type-caption" style={{ color: 'var(--color-ink-tertiary)', marginTop: 6 }}>
              {draftValue.length} characters
            </div>
          </div>
        )}
      </div>
    </div>
  );
}

