// The editable draft never carries the REVIEW STATUS line; the clinician
// review requirement is asked for in the save confirmation dialog instead.
function stripReviewStatus(text) {
  if (!text) return '';
  return text
    .replace(/^[ \t]*REVIEW STATUS:.*$/gim, '')
    .replace(/\n{3,}/g, '\n\n')
    .replace(/^\n+|\s+$/g, '');
}

// Modality literally stated in the dictation, else OPG (the default record
// type in the clinic's data). The user can always override it in the dialog.
function deriveReportType(text = '') {
  if (/\bbitewings?\b/i.test(text)) return 'BITEWING';
  if (/\bcbct\b|cone[- ]beam/i.test(text)) return 'CBCT';
  if (/\bperiapical (?:radiographs?|films?)\b/i.test(text)) return 'PERIAPICAL';
  if (/\bopg\b|orthopantomogram|panoramic/i.test(text)) return 'OPG';
  return 'OPG';
}

// ── New-patient JSON entry ──────────────────────────────────────────────────
// Mirrors the existing patient schema (backend NewPatientInput / patients.json):
// name, dob, gender, phone, email. There is deliberately no "id" field here —
// ids are generated by the backend and a caller-supplied one is never used.

const PATIENT_REQUIRED_JSON_FIELDS = ['name', 'dob', 'gender'];
const PATIENT_OPTIONAL_JSON_FIELDS = ['phone', 'email'];
const PATIENT_JSON_FIELDS = [...PATIENT_REQUIRED_JSON_FIELDS, ...PATIENT_OPTIONAL_JSON_FIELDS];

// Example generated from that schema, offered as a template to copy and edit.
const PATIENT_JSON_EXAMPLE = JSON.stringify({
  name: 'Asha Rao',
  dob: '1990-01-01',
  gender: 'F',
  phone: '+91-98765-00000',
  email: 'asha.rao@example.com',
}, null, 2);

// Current manual-form values rendered as JSON. Empty optional fields become
// null, the same normalisation the backend applies on save.
function patientFormToJson(form) {
  return JSON.stringify({
    name: (form.name || '').trim(),
    dob: form.dob || '',
    gender: form.gender || '',
    phone: (form.phone || '').trim() || null,
    email: (form.email || '').trim() || null,
  }, null, 2);
}

// Parse and validate JSON patient details against the existing patient schema.
// Returns { errors, patient }: `patient` is the normalised payload — identical
// to what the manual form produces, so both modes save through the same
// endpoint — and is only set when there is nothing to report.
function parsePatientJson(text) {
  const source = String(text ?? '');
  if (!source.trim()) {
    return { errors: ['Enter the patient as JSON, or switch to the Manual form.'], patient: null };
  }
  // The untouched example must never reach the database as a real patient.
  if (source.trim() === PATIENT_JSON_EXAMPLE.trim()) {
    return {
      errors: ['This is the example template. Replace it with the real patient details before saving.'],
      patient: null,
    };
  }

  let data;
  try {
    data = JSON.parse(source);
  } catch (err) {
    return { errors: [`Invalid JSON: ${err.message}`], patient: null };
  }
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    return {
      errors: ['The JSON must be a single object, e.g. { "name": "…", "dob": "1990-01-01", "gender": "F" }.'],
      patient: null,
    };
  }

  const errors = [];
  const keys = Object.keys(data);
  if (keys.includes('id')) {
    errors.push('"id" is generated by the server. Remove it: a supplied id is never used, so it cannot create or duplicate a patient.');
  }
  const unknown = keys.filter(k => k !== 'id' && !PATIENT_JSON_FIELDS.includes(k));
  if (unknown.length) {
    errors.push(
      `Unsupported field${unknown.length > 1 ? 's' : ''}: ${unknown.join(', ')}. `
      + `Supported fields: ${PATIENT_JSON_FIELDS.join(', ')}.`
    );
  }

  for (const field of PATIENT_REQUIRED_JSON_FIELDS) {
    const value = data[field];
    if (value === undefined || value === null) {
      errors.push(`"${field}" is required.`);
      continue;
    }
    if (typeof value !== 'string') {
      errors.push(`"${field}" must be a string.`);
      continue;
    }
    if (!value.trim()) errors.push(`"${field}" cannot be empty.`);
  }

  const dob = typeof data.dob === 'string' ? data.dob.trim() : '';
  if (dob && !/^\d{4}-\d{2}-\d{2}$/.test(dob)) {
    errors.push('"dob" must be an ISO date in YYYY-MM-DD format.');
  } else if (dob) {
    const [y, m, d] = dob.split('-').map(Number);
    const probe = new Date(Date.UTC(y, m - 1, d));
    if (probe.getUTCFullYear() !== y || probe.getUTCMonth() !== m - 1 || probe.getUTCDate() !== d) {
      errors.push(`"dob" is not a real calendar date: ${dob}.`);
    }
  }

  for (const field of PATIENT_OPTIONAL_JSON_FIELDS) {
    const value = data[field];
    if (value !== undefined && value !== null && typeof value !== 'string') {
      errors.push(`"${field}" must be a string or null.`);
    }
  }

  if (errors.length) return { errors, patient: null };
  return {
    errors: [],
    patient: {
      name: data.name.trim(),
      dob,
      gender: data.gender.trim(),
      phone: (data.phone || '').trim() || null,
      email: (data.email || '').trim() || null,
    },
  };
}

