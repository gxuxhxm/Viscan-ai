// ── Main App ─────────────────────────────────────────────────────────────────
export default function App() {
  // State
  const [patients, setPatients] = useState([]);
  const [patientsLoading, setPatientsLoading] = useState(true);
  const [search, setSearch] = useState('');
  const [selectedPatient, setSelectedPatient] = useState(null);
  const [reports, setReports] = useState([]);
  const [reportsLoading, setReportsLoading] = useState(false);
  const [activeReport, setActiveReport] = useState(null);
  const [activeReportFull, setActiveReportFull] = useState(null);
  const [reportLoading, setReportLoading] = useState(false);
  // Edited draft text per report id. Held here (not in the detail view) so
  // edits survive navigating away from a report and back; nothing in this map
  // is ever written back onto the saved report.
  const [draftEdits, setDraftEdits] = useState({});

  const [centerTab, setCenterTab] = useState('reports'); // 'reports' | 'report-detail' | 'dictation'
  const [ambiguity, setAmbiguity] = useState(null); // { patients, query }

  const [chatMessages, setChatMessages] = useState([]);
  const [chatLoading, setChatLoading] = useState(false);

  const [dictResult, setDictResult] = useState(null);
  const [dictLoading, setDictLoading] = useState(false);

  const [demoMode, setDemoMode] = useState(false);
  const [backendError, setBackendError] = useState(null);

  // Load patients on mount
  useEffect(() => {
    api.listPatients()
      .then(data => { setPatients(data); setPatientsLoading(false); })
      .catch(() => {
        setPatientsLoading(false);
        setBackendError('Cannot reach backend. Make sure the API is running on port 8000.');
      });
    api.health().then(h => setDemoMode(h.demo_mode)).catch(() => {});
  }, []);

  const filteredPatients = patients.filter(p =>
    p.name.toLowerCase().includes(search.toLowerCase())
  );

  // Report list for one patient, shared by manual selection and by the
  // chatbot's ambiguity resolution, so both flows end up with the same
  // patient/report context in the main panel.
  const loadPatientReports = useCallback(async (patientId) => {
    setReportsLoading(true);
    try {
      const reps = await api.getReports(patientId);
      setReports(reps);
    } catch {
      setReports([]);
    } finally {
      setReportsLoading(false);
    }
  }, []);

  const handleSelectPatient = useCallback(async (p) => {
    setSelectedPatient(p);
    setActiveReport(null);
    setActiveReportFull(null);
    setAmbiguity(null);
    setCenterTab('reports');
    await loadPatientReports(p.id);
  }, [loadPatientReports]);

  const handleSelectReport = useCallback(async (r) => {
    setActiveReport(r);
    setCenterTab('report-detail');
    setReportLoading(true);
    try {
      const full = await api.getReport(r.id);
      setActiveReportFull(full);
    } catch {
      setActiveReportFull(null);
    } finally {
      setReportLoading(false);
    }
  }, []);

  const handleConversationSend = useCallback(async (question) => {
    // Add user message
    setChatMessages(m => [...m, { role: 'user', content: question }]);
    setChatLoading(true);

    try {
      // Always interpret the query WITH session context so intent routing stays
      // correct even while another report is open (e.g. "Open Rohan's bitewing"
      // must open Rohan's report, not be answered as a follow-up about Priya).
      const res = await api.query({
        text: question,
        session_context: activeReportFull?.id ? { active_report_id: activeReportFull.id } : null,
      });

      if (res.ambiguous) {
        // Ambiguous identity → disambiguation card, never a silent pick
        setAmbiguity({ patients: res.matched_patients, query: question });
        setChatMessages(m => [...m, {
          role: 'ai',
          content: res.message,
          evidence: [],
          demo_mode: res.demo_mode,
        }]);
      } else if (res.intent === 'follow_up' && res.report) {
        // Contextual follow-up: answer from the active report, with evidence
        const fu = await api.followUp({ question, report_id: res.report.id });
        setChatMessages(m => [...m, {
          role: 'ai',
          content: fu.answer,
          evidence: fu.evidence,
          source_report_id: fu.source_report_id,
          demo_mode: fu.demo_mode,
        }]);
      } else if (res.report) {
        // Retrieval: auto-open the returned report. A response that carries a
        // report IS the successful resolution of any pending ambiguity (e.g.
        // the user just answered "Priya Sharma"), so the selection panel closes
        // here and only here. A still-ambiguous reply (branch above) or a
        // response without a report keeps the panel so the user can retry.
        setActiveReportFull(res.report);
        setActiveReport(res.report);
        setCenterTab('report-detail');
        if (res.matched_patients?.[0]) {
          setSelectedPatient(res.matched_patients[0]);
          // Keep the main panel's report list in step with the chatbot's pick
          // so "← All reports" shows this patient, not the previous one.
          void loadPatientReports(res.matched_patients[0].id);
        }
        setAmbiguity(null);
        setChatMessages(m => [...m, {
          role: 'ai',
          content: res.message,
          evidence: [],
          source_report_id: res.report.id,
          demo_mode: res.demo_mode,
        }]);
      } else {
        setChatMessages(m => [...m, {
          role: 'ai',
          content: res.message,
          evidence: [],
          demo_mode: res.demo_mode,
        }]);
      }
    } catch (err) {
      setChatMessages(m => [...m, {
        role: 'ai',
        content: `Error: ${err.message}. Please check the backend is running.`,
        evidence: [],
      }]);
    } finally {
      setChatLoading(false);
    }
  }, [activeReportFull, loadPatientReports]);

  const handleDictationSubmit = useCallback(async (transcript) => {
    setDictLoading(true);
    setDictResult(null);
    try {
      const res = await api.dictation({ transcript });
      setDictResult(res);
    } catch (err) {
      setDictResult({
        findings: [],
        anatomical_site: 'Error',
        draft_report: `Failed to process dictation: ${err.message}`,
        uncertainties: ['Backend error'],
        requires_review: true,
        demo_mode: true,
        // An error message is never a report: no draft, no save.
        usable: false,
      });
    } finally {
      setDictLoading(false);
    }
  }, []);

  // Clearing the dictation drops the structured summary too, so the stale
  // findings can never be saved after the draft is gone. The transcript itself
  // is cleared inside the panel; only the saved reports on the backend stay.
  const handleDictationClear = useCallback(() => setDictResult(null), []);

  // Draft edits are local only: they update the in-memory map for that report
  // and are exported as a .txt file, never posted back to the backend.
  const handleDraftChange = useCallback((reportId, text) => {
    setDraftEdits(m => (m[reportId] === text ? m : { ...m, [reportId]: text }));
  }, []);

  const handleAmbiguitySelect = useCallback(async (patient) => {
    setAmbiguity(null);
    await handleSelectPatient(patient);
  }, [handleSelectPatient]);

  // After a dictation report is saved: a new patient (if any) joins the
  // existing list, and the open patient's report list picks up the new report.
  const handleReportSaved = useCallback(async (saved) => {
    try {
      setPatients(await api.listPatients());
    } catch {
      // The save itself already succeeded; a stale sidebar is non-fatal.
    }
    if (saved?.patient_id && saved.patient_id === selectedPatient?.id) {
      try {
        setReports(await api.getReports(saved.patient_id));
      } catch {
        // Non-fatal: the saved report is still reachable via the normal flow.
      }
    }
  }, [selectedPatient]);

  // ── Render ─────────────────────────────────────────────────────────────────
  const detailReport = activeReportFull || activeReport;
  return (
    <>
      {/* Top nav */}
      <nav className="top-nav">
        {/* The brand block and the trailing spacer are both flexible (flex: 1),
            so the tab group sits on the true centre line of the bar. Two equal
            `flex: 1` spacers around it would instead centre the group *within
            the leftover space*, pushing it right by half the brand width. */}
        <div style={{ display: 'flex', alignItems: 'center', gap: 8, flex: 1, minWidth: 0 }}>
          <div style={{
            width: 28, height: 28, borderRadius: 'var(--radius-sm)',
            background: 'var(--color-fin-orange)', flexShrink: 0,
            display: 'flex', alignItems: 'center', justifyContent: 'center',
          }}>
            <Radio size={15} color="white" />
          </div>
          <span className="type-eyebrow" style={{ color: 'var(--color-ink)', whiteSpace: 'nowrap' }}>Viscan AI</span>
          <span className="type-caption" style={{ color: 'var(--color-ink-tertiary)', marginLeft: 4, whiteSpace: 'nowrap' }}>Dental Reporting AI</span>
        </div>

        {/* Tab group for center panel */}
        <div className="tab-group">
          <button className={`tab-item ${centerTab !== 'dictation' ? 'active' : ''}`}
            onClick={() => setCenterTab(activeReport ? 'report-detail' : 'reports')}
            style={{ gap: 4 }}>
            <FileText size={13} /> Reports
          </button>
          <button className={`tab-item ${centerTab === 'dictation' ? 'active' : ''}`}
            onClick={() => setCenterTab('dictation')}
            style={{ gap: 4 }}>
            <Mic size={13} /> Dictation
          </button>
        </div>

        <div style={{ flex: 1 }} />
      </nav>

      {/* Demo banner */}
      {demoMode && <DemoBanner />}

      {/* Backend error */}
      {backendError && (
        <div className="backend-error-bar" style={{ background: '#fef2f2', borderBottom: '1px solid #fecaca', padding: '8px 24px', color: '#991b1b', fontSize: 13, display: 'flex', alignItems: 'center', gap: 8 }}>
          <AlertTriangle size={14} /> {backendError}
        </div>
      )}

      {/* Main 3-panel layout */}
      <div className="app-layout">
        {/* LEFT: Patient list */}
        <PatientSidebar
          patients={filteredPatients}
          loading={patientsLoading}
          selectedPatientId={selectedPatient?.id}
          onSelect={handleSelectPatient}
          searchValue={search}
          onSearchChange={setSearch}
        />

        {/* CENTER: Reports / detail / dictation */}
        <div className="panel-center">
          {/* Patient header */}
          {selectedPatient && centerTab !== 'dictation' && (
            <div style={{
              padding: '12px 24px', borderBottom: '1px solid var(--color-hairline-soft)',
              display: 'flex', alignItems: 'center', gap: 10, flexShrink: 0,
              background: 'var(--color-surface-1)',
            }}>
              <div className="patient-avatar">{initials(selectedPatient.name)}</div>
              <div>
                <div className="type-body" style={{ fontWeight: 500 }}>{selectedPatient.name}</div>
                <div className="type-caption" style={{ color: 'var(--color-ink-muted)' }}>
                  {selectedPatient.gender} · DOB {formatDate(selectedPatient.dob)}
                  {selectedPatient.phone && <> · {selectedPatient.phone}</>}
                </div>
              </div>
              {activeReport && (
                <button className="btn-secondary" onClick={() => { setActiveReport(null); setActiveReportFull(null); setCenterTab('reports'); }}
                  style={{ marginLeft: 'auto', fontSize: 13, padding: '6px 12px' }}>
                  ← All reports
                </button>
              )}
            </div>
          )}

          {/* Ambiguity resolver */}
          {ambiguity && (
            <AmbiguityCard
              patients={ambiguity.patients}
              query={ambiguity.query}
              onSelect={handleAmbiguitySelect}
              onDismiss={() => setAmbiguity(null)}
            />
          )}

          {/* Content */}
          <div className="scroll-y" style={{ flex: 1 }}>
            {centerTab === 'dictation' && (
              <DictationPanel
                result={dictResult}
                loading={dictLoading}
                onSubmit={handleDictationSubmit}
                patients={patients}
                selectedPatient={selectedPatient}
                onReportSaved={handleReportSaved}
                onClearResult={handleDictationClear}
              />
            )}

            {centerTab === 'reports' && !selectedPatient && (
              <div style={{ padding: 48, textAlign: 'center', color: 'var(--color-ink-muted)' }}>
                <div style={{
                  width: 64, height: 64, borderRadius: 'var(--radius-xl)',
                  background: 'var(--color-surface-1)', border: '1px solid var(--color-hairline)',
                  display: 'flex', alignItems: 'center', justifyContent: 'center',
                  margin: '0 auto 16px',
                }}>
                  <User size={28} style={{ color: 'var(--color-ink-tertiary)' }} />
                </div>
                <h2 className="type-headline" style={{ marginBottom: 8 }}>Select a patient</h2>
                <p className="type-body" style={{ color: 'var(--color-ink-muted)', marginBottom: 24 }}>
                  Choose a patient from the sidebar, or type a query in the AI panel.
                </p>
                <p className="type-body-sm" style={{ color: 'var(--color-ink-tertiary)' }}>
                  Try: "Open Priya's latest OPG report"
                </p>
              </div>
            )}

            {centerTab === 'reports' && selectedPatient && (
              <ReportList
                reports={reports}
                loadingReports={reportsLoading}
                onSelect={handleSelectReport}
                activeReportId={activeReport?.id}
              />
            )}

            {centerTab === 'report-detail' && (
              reportLoading
                ? <div style={{ padding: 24 }}>
                    <Skeleton h={20} w="60%" mb={12} />
                    <Skeleton h={14} w="40%" mb={24} />
                    <Skeleton h={100} mb={12} />
                    <Skeleton h={80} mb={12} />
                    <Skeleton h={200} />
                  </div>
                : <ReportDetail
                    report={detailReport}
                    patient={selectedPatient}
                    draftText={detailReport ? draftEdits[detailReport.id] : undefined}
                    onDraftChange={handleDraftChange}
                  />
            )}
          </div>
        </div>

        {/* RIGHT: Conversation */}
        <ConversationPanel
          messages={chatMessages}
          loading={chatLoading}
          activeReportId={activeReportFull?.id}
          onSend={handleConversationSend}
        />
      </div>
    </>
  );
}
